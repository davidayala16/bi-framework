"""Generate warehouse-native semantic layer definitions from the registry.

    python scripts/export_semantic_layer.py            # (re)write the files
    python scripts/export_semantic_layer.py --check    # fail if they're stale

Writes, under platforms/semantic_layer/:
  snowflake/bi_framework_metrics.semantic_view.sql
      one CREATE SEMANTIC VIEW covering every registry metric
  databricks/<view>.metric_view.yaml
      one Unity Catalog metric view YAML per mart (a metric view has a
      single source, so the metrics are split by the table they aggregate)
  databricks/create_metric_views.sql
      the CREATE VIEW ... WITH METRICS LANGUAGE YAML wrapper for each

Where the content comes from:
  metrics/registry.yaml            which metrics exist, and each one's id,
                                   name, description, owner, and unit
  platforms/dbt/models/**/*.yml    `meta.semantic`: how each metric is
                                   expressed as an aggregate over a dbt
                                   mart, and each mart's key and dimensions

No metric expression is written in this script. A registry metric with no
`meta.semantic` mapping is an error, not an omission, and
tests/test_semantic_layer_export.py runs every mapped expression on DuckDB
against resolve_metric(), so the exported definitions can't drift from the
registry.

Both targets read only the dbt-built `analytics` schema, like LookML.

Status: both syntaxes were checked against the vendors' current
documentation, but the generated files have not been executed against a
live Snowflake or Databricks account. See platforms/semantic_layer/README.md.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from metrics.resolver import load_registry  # noqa: E402

DBT_MODELS = REPO_ROOT / "platforms" / "dbt" / "models"
OUT_DIR = REPO_ROOT / "platforms" / "semantic_layer"
ANALYTICS_SCHEMA = "analytics"
SNOWFLAKE_VIEW = "bi_framework_metrics"
DEFAULT_DATABRICKS_CATALOG = "workspace"

GENERATED_NOTE = (
    "GENERATED by scripts/export_semantic_layer.py from metrics/registry.yaml "
    "and the dbt `meta.semantic` mappings. Do not edit by hand; change the "
    "registry or the mapping and regenerate."
)


class SemanticExportError(ValueError):
    pass


@dataclass
class Table:
    model: str  # dbt model name, e.g. fct_order_items
    alias: str  # logical table name, e.g. order_items
    description: str
    primary_key: list[str]
    dimensions: list[str]
    column_descriptions: dict[str, str]
    relationships: list[dict] = field(default_factory=list)


@dataclass
class Metric:
    id: str
    name: str
    description: str
    owner: str
    unit: str
    table: str  # dbt model name
    expr: str
    group_by: dict[str, str]  # registry output column -> mart column
    note: str = ""

    @property
    def comment(self) -> str:
        text = f"{self.name}. {self.description}"
        if self.group_by:
            text += " Group by " + ", ".join(self.group_by.values()) + "."
        if self.note:
            text += f" {self.note}"
        return f"{text} [registry:{self.id}; owner: {self.owner}; unit: {self.unit}]"


def _one_line(text: str | None) -> str:
    return " ".join((text or "").split())


def _dbt_models() -> dict[str, dict]:
    models: dict[str, dict] = {}
    for path in sorted(DBT_MODELS.rglob("*.yml")):
        for model in (yaml.safe_load(path.read_text()) or {}).get("models", []):
            models[model["name"]] = model
    return models


def load_semantic_model() -> tuple[dict[str, Table], list[Metric]]:
    """Join the registry to the dbt `meta.semantic` mappings."""
    dbt_models = _dbt_models()

    tables: dict[str, Table] = {}
    for name, model in dbt_models.items():
        sem = (model.get("meta") or {}).get("semantic")
        if not sem or "alias" not in sem:
            continue
        tables[name] = Table(
            model=name,
            alias=sem["alias"],
            description=_one_line(model.get("description")),
            primary_key=list(sem["primary_key"]),
            dimensions=list(sem["dimensions"]),
            column_descriptions={
                c["name"]: _one_line(c["description"])
                for c in model.get("columns", [])
                if c.get("description")
            },
            relationships=list(sem.get("relationships", [])),
        )

    mappings = {}
    for model in dbt_models.values():
        meta = model.get("meta") or {}
        if "registry_id" in meta and "semantic" in meta:
            mappings[meta["registry_id"]] = meta["semantic"]

    metrics = []
    for entry in load_registry()["metrics"]:
        sem = mappings.get(entry["id"])
        if sem is None:
            raise SemanticExportError(
                f"registry metric {entry['id']!r} has no `meta.semantic` mapping in "
                "platforms/dbt/models/metrics/_metrics.yml"
            )
        if sem["table"] not in tables:
            raise SemanticExportError(
                f"{entry['id']}: semantic table {sem['table']!r} has no `meta.semantic` "
                "block in platforms/dbt/models/marts/_marts.yml"
            )
        group_by = dict(sem.get("group_by") or {})
        undeclared = set(group_by.values()) - set(tables[sem["table"]].dimensions)
        if undeclared:
            raise SemanticExportError(
                f"{entry['id']}: group_by columns {undeclared} are not dimensions of {sem['table']}"
            )
        metrics.append(
            Metric(
                id=entry["id"],
                name=entry["name"],
                description=_one_line(entry["description"]),
                owner=entry["owner"],
                unit=entry["unit"],
                table=sem["table"],
                expr=_one_line(sem["expr"]),
                group_by=group_by,
                note=_one_line(sem.get("note")),
            )
        )
    return tables, metrics


# --- Snowflake: CREATE SEMANTIC VIEW -----------------------------------------


def _sql_string(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render_snowflake(tables: dict[str, Table], metrics: list[Metric]) -> str:
    used = [t for t in tables.values() if any(m.table == t.model for m in metrics)]

    table_entries = [
        f"    {t.alias} AS {ANALYTICS_SCHEMA}.{t.model}\n"
        f"      PRIMARY KEY ({', '.join(t.primary_key)})\n"
        f"      COMMENT = {_sql_string(t.description)}"
        for t in used
    ]
    relationship_entries = [
        f"    {r['name']} AS\n"
        f"      {t.alias} ({r['column']}) REFERENCES {tables[r['to']].alias}"
        for t in used
        for r in t.relationships
        if tables[r["to"]] in used
    ]
    dimension_entries = []
    for t in used:
        for column in t.dimensions:
            entry = f"    {t.alias}.{column} AS {t.alias}.{column}"
            if column in t.column_descriptions:
                entry += f"\n      COMMENT = {_sql_string(t.column_descriptions[column])}"
            dimension_entries.append(entry)
    metric_entries = [
        f"    {tables[m.table].alias}.{m.id} AS {m.expr}\n"
        f"      COMMENT = {_sql_string(m.comment)}"
        for m in metrics
    ]

    example = metrics[0]
    example_table = tables[example.table]
    lines = [
        f"-- {GENERATED_NOTE}",
        "--",
        "-- Snowflake semantic view over the dbt-built `analytics` schema. Run it",
        "-- in the database dbt built into (SNOWFLAKE_DATABASE), after",
        "-- `dbt build --target snowflake`. Each metric is named after its",
        "-- registry id.",
        "--",
        "-- Query it with the SEMANTIC_VIEW clause, for example:",
        f"--   SELECT * FROM SEMANTIC_VIEW(",
        f"--     {ANALYTICS_SCHEMA}.{SNOWFLAKE_VIEW}",
        f"--     METRICS {example_table.alias}.{example.id}",
        f"--     DIMENSIONS {example_table.alias}.{example_table.dimensions[1]}",
        "--   );",
        "",
        f"CREATE OR REPLACE SEMANTIC VIEW {ANALYTICS_SCHEMA}.{SNOWFLAKE_VIEW}",
        "  TABLES (",
        ",\n".join(table_entries),
        "  )",
    ]
    if relationship_entries:
        lines += ["  RELATIONSHIPS (", ",\n".join(relationship_entries), "  )"]
    lines += [
        "  DIMENSIONS (",
        ",\n".join(dimension_entries),
        "  )",
        "  METRICS (",
        ",\n".join(metric_entries),
        "  )",
        "  COMMENT = "
        + _sql_string(
            "Governed metrics for the bi-framework demo. Generated from "
            "metrics/registry.yaml; the registry is the definition of record."
        )
        + ";",
        "",
    ]
    return "\n".join(lines)


# --- Databricks: Unity Catalog metric views ----------------------------------


def databricks_view_name(table: Table) -> str:
    return f"{table.alias}_metrics"


def render_databricks_yaml(table: Table, metrics: list[Metric], catalog: str) -> str:
    spec = {
        "version": 1.1,
        "comment": f"{table.description} Generated from metrics/registry.yaml.",
        "source": f"{catalog}.{ANALYTICS_SCHEMA}.{table.model}",
        "dimensions": [
            {"name": column, "expr": column}
            | (
                {"comment": table.column_descriptions[column]}
                if column in table.column_descriptions
                else {}
            )
            for column in table.dimensions
        ],
        "measures": [{"name": m.id, "expr": m.expr, "comment": m.comment} for m in metrics],
    }
    body = yaml.safe_dump(spec, sort_keys=False, width=88, allow_unicode=True)
    return f"# {GENERATED_NOTE}\n{body}"


def render_databricks_sql(yamls: dict[str, str], catalog: str) -> str:
    first_view, first_yaml = next(iter(yamls.items()))
    spec = yaml.safe_load(first_yaml)
    lines = [
        f"-- {GENERATED_NOTE}",
        "--",
        "-- Unity Catalog metric views over the dbt-built `analytics` schema. Run",
        "-- after `dbt build --target databricks`. Each YAML body below is the",
        "-- matching <view>.metric_view.yaml file, verbatim. Each measure is named",
        "-- after its registry id.",
        "--",
        "-- Query a metric view with MEASURE(), for example:",
        f"--   SELECT {spec['dimensions'][1]['name']}, MEASURE({spec['measures'][0]['name']})",
        f"--   FROM {catalog}.{ANALYTICS_SCHEMA}.{first_view}",
        "--   GROUP BY ALL;",
    ]
    for view, body in yamls.items():
        lines += [
            "",
            f"CREATE OR REPLACE VIEW {catalog}.{ANALYTICS_SCHEMA}.{view}",
            "WITH METRICS",
            "LANGUAGE YAML",
            "AS $$",
            body.rstrip("\n"),
            "$$;",
        ]
    return "\n".join(lines) + "\n"


def render_all(catalog: str = DEFAULT_DATABRICKS_CATALOG) -> dict[Path, str]:
    """Every generated file, keyed by its path."""
    tables, metrics = load_semantic_model()
    files = {
        OUT_DIR / "snowflake" / f"{SNOWFLAKE_VIEW}.semantic_view.sql": render_snowflake(
            tables, metrics
        )
    }
    yamls = {}
    for table in tables.values():
        table_metrics = [m for m in metrics if m.table == table.model]
        if not table_metrics:
            continue
        view = databricks_view_name(table)
        yamls[view] = render_databricks_yaml(table, table_metrics, catalog)
        files[OUT_DIR / "databricks" / f"{view}.metric_view.yaml"] = yamls[view]
    files[OUT_DIR / "databricks" / "create_metric_views.sql"] = render_databricks_sql(
        yamls, catalog
    )
    return files


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--catalog",
        default=DEFAULT_DATABRICKS_CATALOG,
        help="Unity Catalog catalog the Databricks metric views read from and "
        f"are created in (default: {DEFAULT_DATABRICKS_CATALOG})",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 if the committed files are out of date",
    )
    args = parser.parse_args(argv)

    try:
        files = render_all(args.catalog)
    except SemanticExportError as exc:
        sys.exit(str(exc))

    if args.check:
        stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            names = ", ".join(str(p.relative_to(REPO_ROOT)) for p in stale)
            sys.exit(f"Out of date: {names}. Run python scripts/export_semantic_layer.py")
        print(f"{len(files)} generated files are up to date")
        return

    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
